import assert from 'node:assert/strict';
const { QueryClient } = await import(new URL('../../../../web/node_modules/@tanstack/react-query/build/modern/index.js', import.meta.url));
const { createServerLedgerClient, prefetchBalances, ledgerKeys } = await import(new URL('../../../../web/packages/ledger-react/dist/server.js', import.meta.url));
let callsA = 0, callsB = 0;
const a = createServerLedgerClient({baseUrl:'https://a.invalid', fetch:async()=>{callsA++;return Response.json({code:200,message:null,data:{list:[{balance:'100',source:'A'}]}})}});
const b = createServerLedgerClient({baseUrl:'https://b.invalid', fetch:async()=>{callsB++;return Response.json({code:200,message:null,data:{list:[{balance:'999',source:'B'}]}})}});
const qc = new QueryClient({defaultOptions:{queries:{staleTime:60_000}}});
await prefetchBalances(qc,a,42);
await prefetchBalances(qc,b,42);
const reused = qc.getQueryData(ledgerKeys.balances(42));
assert.equal(callsA,1); assert.equal(callsB,0); assert.equal(reused[0].source,'A');
console.log(JSON.stringify({probe:'cross-instance-cache',callsA,callsB,dataForB:reused}));
let wire;
const client=createServerLedgerClient({baseUrl:'https://ledger.invalid',fetch:async(url,init)=>{wire=JSON.parse(init.body);return Response.json({code:200,message:null,data:{}})}});
await client.createReservation({account_holder:42,currency_uid:'018fffd9-0000-7000-8000-000000000001',amount:'10',idempotency_key:'library-review-expiry',expires_in:'1h'});
assert.equal(wire.expires_in,'1h'); assert.equal(wire.expires_in_sec,undefined);
console.log(JSON.stringify({probe:'reservation-client-wire',wire}));
qc.clear();
let holderRequest;
const idClient=createServerLedgerClient({baseUrl:'https://ledger.invalid',fetch:async(url,init)=>{holderRequest=JSON.parse(init.body);return Response.json({code:200,message:null,data:{}})}});
const holderFromText=parseInt('9007199254740993', 10);
await idClient.postTemplateJournal({template_code:'transfer',holder_id:holderFromText,currency_uid:'018fffd9-0000-7000-8000-000000000001',idempotency_key:'holder-precision-probe',amounts:{amount:'10'}});
assert.equal(String(holderRequest.holder_id),'9007199254740992');
console.log(JSON.stringify({probe:'holder-id-roundtrip',intended:'9007199254740993',actual:String(holderRequest.holder_id),wire:holderRequest}));
