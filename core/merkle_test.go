func TestBuildMerkleTree_SharesEncodingWithCanonicalBatchDigest(t *testing.T) {
	// Not a golden vector -- a structural pin: changing one entry's amount
	// must change the Merkle root (proving the leaf actually depends on
	// the full entry payload, the same fields CanonicalBatchDigest hashes,
	// not some subset).
	entries := []AttestedEntry{
		{EntryID: 1, JournalID: 1, AccountHolder: 100, CurrencyID: 1, ClassificationID: 1, EntryType: EntryTypeDebit, Amount: decimal.NewFromInt(10), EffectiveAt: time.Date(2026, 8, 21, 0, 0, 0, 0, time.UTC)},
		{EntryID: 2, JournalID: 1, AccountHolder: 200, CurrencyID: 1, ClassificationID: 2, EntryType: EntryTypeCredit, Amount: decimal.NewFromInt(10), EffectiveAt: time.Date(2026, 8, 21, 0, 0, 0, 0, time.UTC)},
	}
	treeA, err := BuildMerkleTree(entries)
	if err != nil {
		t.Fatalf("BuildMerkleTree: %v", err)
	}

	modified := make([]AttestedEntry, len(entries))
	copy(modified, entries)
	modified[0].Amount = modified[0].Amount.Add(decimal.NewFromInt(1))
	treeB, err := BuildMerkleTree(modified)
	if err != nil {
		t.Fatalf("BuildMerkleTree: %v", err)
	}

	if hex.EncodeToString(treeA.Root()) == hex.EncodeToString(treeB.Root()) {
		t.Error("changing an entry's amount did not change the Merkle root")
	}
}
